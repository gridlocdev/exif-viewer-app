namespace ExifViewer.Core.Tiff;

/// <summary>Which tag numbering an IFD uses. TIFF and Exif IFDs share one numbering; GPS and Interop have their own.</summary>
internal enum TagSet { Tiff, Gps, Interop }

/// <summary>Display names for tag numbers, from the TIFF 6.0, Exif 3.0 and DNG specifications.</summary>
internal static class TagNames
{
    public static string Get(TagSet set, ushort tag)
    {
        var table = set switch
        {
            TagSet.Gps => Gps,
            TagSet.Interop => Interop,
            _ => Tiff,
        };
        return table.TryGetValue(tag, out var name) ? name : $"Unknown 0x{tag:X4}";
    }

